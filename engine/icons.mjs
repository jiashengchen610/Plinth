// Icons: the SVG files in a workspace's icons/ folder are the source of truth; src/icons/index.tsx is generated
// from them (one React component per file, named <Pascal>Icon), and components import icons only from there.
// Icons come from a set Plinth ships (Lucide, ISC) or from the user's own SVG files; nothing references an icon
// package. Zero dependencies: the SVG files are simple enough to read with patterns.
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
let lucide = null;
/** The Lucide set Plinth ships: { name, version, license, size, aliases, icons: { name: [[tag, attrs]] } }. */
export function iconSet() {
  lucide ??= JSON.parse(readFileSync(join(here, "icon-sets", "lucide.json"), "utf8"));
  return lucide;
}

const ATTRS = { xmlns: "http://www.w3.org/2000/svg", width: "24", height: "24", viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round" };
const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${esc(v)}"`).join(" ");

/** An icon of the shipped set as an SVG file. */
export function setIconSvg(name) {
  const set = iconSet();
  const real = set.icons[name] ? name : set.aliases[name];
  if (!real) return null;
  const body = set.icons[real].map(([tag, a]) => `  <${tag} ${attrs(a)} />`).join("\n");
  return `<svg ${attrs(ATTRS)}>\n${body}\n</svg>\n`;
}

/** Names in the set matching words of a query, best first ("alert" → circle-alert, triangle-alert …). */
export function findIcons(query, limit = 30) {
  const set = iconSet();
  const words = String(query ?? "").toLowerCase().split(/[\s,]+/).filter(Boolean);
  if (!words.length) return [];
  const names = [...Object.keys(set.icons), ...Object.keys(set.aliases)];
  const score = (n) => words.reduce((s, w) => s + (n === w ? 10 : n.split("-").includes(w) ? 5 : n.includes(w) ? 2 : 0), 0);
  return names.map((n) => [n, score(n)]).filter(([, s]) => s > 0).sort((a, b) => b[1] - a[1] || a[0].length - b[0].length).slice(0, limit).map(([n]) => n);
}

/** Ops that vendor icons from the set into icons/. Unknown names throw with suggestions. */
export function addIconOps(root, names) {
  const ops = [];
  for (const name of names) {
    const n = String(name).trim().toLowerCase();
    const svg = setIconSvg(n);
    if (!svg) {
      const near = findIcons(n.replace(/-/g, " "), 5);
      throw new Error(`No icon "${name}" in ${iconSet().name}.${near.length ? ` Close: ${near.join(", ")}.` : ""}`);
    }
    if (!existsSync(join(root, "icons", `${n}.svg`))) ops.push({ op: "write", file: `icons/${n}.svg`, content: svg });
  }
  return ops;
}

const pascal = (n) => n.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((s) => s[0].toUpperCase() + s.slice(1)).join("");
/** stroke-width → strokeWidth; class → className; xlink:href → xlinkHref. */
const jsxName = (k) => (k === "class" ? "className" : k.replace(/[:-]([a-z])/g, (_, c) => c.toUpperCase()));
const parseAttrs = (s) => Object.fromEntries([...s.matchAll(/([a-zA-Z_:][\w:.-]*)\s*=\s*"([^"]*)"/g)].map((m) => [m[1], m[2]]));
const SHAPES = /<(path|circle|rect|line|polyline|polygon|ellipse|g|\/g)\b([^>]*?)\/?>/g;

/** One SVG file → { root attributes, children as JSX }, or null when it is not an SVG Plinth can read. */
export function readSvg(text) {
  const open = /<svg\b([^>]*)>/.exec(text);
  if (!open) return null;
  const root = parseAttrs(open[1]);
  const children = [];
  for (const m of text.slice(open.index + open[0].length).matchAll(SHAPES)) {
    if (m[1] === "/g") { children.push("</g>"); continue; }
    const a = Object.entries(parseAttrs(m[2])).map(([k, v]) => `${jsxName(k)}="${esc(v)}"`).join(" ");
    children.push(m[1] === "g" && !m[0].endsWith("/>") ? `<g ${a}>` : `<${m[1]}${a ? ` ${a}` : ""} />`);
  }
  return { root, children: children.join("") };
}

/** The generated module: src/icons/index.tsx. Stable output (sorted) so the CI can compare it. */
export function iconsModule(root) {
  const dir = join(root, "icons");
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^[a-z0-9-]+\.svg$/.test(f)).sort() : [];
  const lines = [
    "// Generated by Plinth from the SVG files in icons/. Do not edit: add, change or remove files in icons/ instead.",
    'import * as React from "react";',
    "",
    "export type IconProps = React.SVGProps<SVGSVGElement> & { size?: number | string };",
    "",
    "function Svg({ size = 24, children, ...props }: IconProps) {",
    '  return <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" focusable="false" {...props}>{children}</svg>;',
    "}",
    "",
  ];
  const names = [];
  for (const f of files) {
    const svg = readSvg(readFileSync(join(dir, f), "utf8"));
    if (!svg) continue;
    const name = `${pascal(f.replace(/\.svg$/, ""))}Icon`;
    names.push([f.replace(/\.svg$/, ""), name]);
    const keep = Object.entries(svg.root).filter(([k]) => ["viewBox", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin"].includes(k) && svg.root[k] !== ATTRS[k]);
    const extra = keep.map(([k, v]) => `${jsxName(k)}="${esc(v)}"`).join(" ");
    lines.push(`export function ${name}(props: IconProps) {`, `  return <Svg${extra ? ` ${extra}` : ""} {...props}>${svg.children}</Svg>;`, "}", "");
  }
  lines.push("/** Every icon by file name, for galleries and pickers. */", "export const icons = {", ...names.map(([file, name]) => `  ${JSON.stringify(file)}: ${name},`), "} as const;", "");
  return lines.join("\n");
}

/** Icon files in the workspace, for the UI and tools. */
export function listIcons(root) {
  const dir = join(root, "icons");
  return existsSync(dir) ? readdirSync(dir).filter((f) => /^[a-z0-9-]+\.svg$/.test(f)).map((f) => f.replace(/\.svg$/, "")).sort() : [];
}
